-- ---------------- Create order from server only ----------------
-- No stock is decremented here. This prevents an attacker from exhausting
-- stock by generating unpaid orders. Stock is decremented atomically only
-- after a valid YooMoney webhook is received.
create or replace function public.create_yoomoney_order(
  p_items jsonb,
  p_payment_type text
)
returns table (
  order_id uuid,
  order_label text,
  total_amount numeric
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order_id uuid := gen_random_uuid();
  v_label text := 'WR-' || replace(v_order_id::text, '-', '');
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
  v_total numeric(12,2) := 0;
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'EMPTY_CART';
  end if;

  if p_payment_type not in ('AC','PC') then
    raise exception 'INVALID_PAYMENT_TYPE';
  end if;

  insert into public.orders(id, label, status, amount, payment_type)
  values(v_order_id, v_label, 'pending', 0, p_payment_type);

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_qty := greatest(1, least(100, coalesce((v_item->>'quantity')::integer, 1)));

    select *
    into v_product
    from public.products
    where id = (v_item->>'product_id')::uuid;

    if not found then
      raise exception 'PRODUCT_NOT_FOUND';
    end if;

    if v_product.stock < v_qty then
      raise exception 'NOT_ENOUGH_STOCK:%', v_product.title;
    end if;

    v_total := v_total + (v_product.price * v_qty);

    insert into public.order_items(
      order_id,
      product_id,
      product_title,
      unit_price,
      quantity
    ) values (
      v_order_id,
      v_product.id,
      v_product.title,
      v_product.price,
      v_qty
    );
  end loop;

  update public.orders
  set amount = v_total
  where id = v_order_id;

  return query select v_order_id, v_label, v_total;
end;
$$;

revoke all on function public.create_yoomoney_order(jsonb,text) from public, anon, authenticated;
grant execute on function public.create_yoomoney_order(jsonb,text) to service_role;

-- ---------------- Complete paid order ----------------
-- Idempotent. Locks the order and affected products.
-- If stock became insufficient after the customer paid, the order is marked
-- paid_manual_review instead of silently losing the payment.
create or replace function public.complete_yoomoney_order(
  p_label text,
  p_operation_id text,
  p_received_amount numeric,
  p_withdraw_amount numeric
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_item record;
  v_product public.products%rowtype;
begin
  select *
  into v_order
  from public.orders
  where label = p_label
  for update;

  if not found then
    return 'ORDER_NOT_FOUND';
  end if;

  if v_order.status = 'paid' then
    return 'ALREADY_PAID';
  end if;

  if v_order.status = 'paid_manual_review' then
    return 'ALREADY_REVIEW';
  end if;

  if v_order.status <> 'pending' then
    return 'ORDER_NOT_PENDING';
  end if;

  -- withdraw_amount is what the sender actually paid.
  if abs(coalesce(p_withdraw_amount,0) - v_order.amount) > 0.01 then
    return 'AMOUNT_MISMATCH';
  end if;

  -- Lock every product and make sure stock is still enough.
  for v_item in
    select *
    from public.order_items
    where order_id = v_order.id
    order by product_id
  loop
    select *
    into v_product
    from public.products
    where id = v_item.product_id
    for update;

    if not found or v_product.stock < v_item.quantity then
      update public.orders
      set
        status = 'paid_manual_review',
        yoomoney_operation_id = p_operation_id,
        received_amount = p_received_amount,
        withdraw_amount = p_withdraw_amount,
        paid_at = now()
      where id = v_order.id;

      return 'PAID_MANUAL_REVIEW';
    end if;
  end loop;

  -- All stock is available: decrement it.
  for v_item in
    select *
    from public.order_items
    where order_id = v_order.id
  loop
    update public.products
    set
      stock = stock - v_item.quantity,
      updated_at = now()
    where id = v_item.product_id;
  end loop;

  update public.orders
  set
    status = 'paid',
    yoomoney_operation_id = p_operation_id,
    received_amount = p_received_amount,
    withdraw_amount = p_withdraw_amount,
    paid_at = now()
  where id = v_order.id;

  return 'PAID';
end;
$$;

revoke all on function public.complete_yoomoney_order(text,text,numeric,numeric) from public, anon, authenticated;
grant execute on function public.complete_yoomoney_order(text,text,numeric,numeric) to service_role;

-- ---------------- Admin cancel ----------------
create or replace function public.cancel_pending_order(p_order_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'NOT_ADMIN';
  end if;

  update public.orders
  set status = 'cancelled'
  where id = p_order_id
    and status = 'pending';

  if not found then
    raise exception 'ORDER_NOT_PENDING';
  end if;
end;
$$;

revoke all on function public.cancel_pending_order(uuid) from public, anon;
grant execute on function public.cancel_pending_order(uuid) to authenticated;


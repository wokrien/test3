create extension if not exists pgcrypto;

-- ---------------- Products ----------------
create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text not null default '',
  price numeric(12,2) not null default 0 check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  badge text not null default 'Предмет',
  icon text not null default '✦',
  popularity integer not null default 80 check (popularity between 0 and 100),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ---------------- Admin users ----------------
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

-- ---------------- Orders ----------------
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  label text not null unique,
  status text not null default 'pending'
    check (status in ('pending','paid','paid_manual_review','cancelled')),
  amount numeric(12,2) not null default 0 check (amount >= 0),
  received_amount numeric(12,2),
  withdraw_amount numeric(12,2),
  yoomoney_operation_id text unique,
  payment_type text,
  created_at timestamptz not null default now(),
  paid_at timestamptz
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_title text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0)
);

create index if not exists idx_orders_label on public.orders(label);
create index if not exists idx_orders_created_at on public.orders(created_at desc);
create index if not exists idx_order_items_order_id on public.order_items(order_id);

-- ---------------- Helper: admin check ----------------
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = auth.uid()
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

-- ---------------- RLS ----------------
